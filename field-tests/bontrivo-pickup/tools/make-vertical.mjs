#!/usr/bin/env node
// make-vertical.mjs (film 3): the 9:16 cut. Unlike films 1-2, nothing is string-patched:
// every frame already carries both layouts (tools/frames.py writes the 9:16 rules under
// `#root[data-width="1080"]`, and split.js reads the declared size for the few numbers a
// timeline needs). This script only copies the frames into vertical/ with the root's
// declared size swapped, and checks that each frame really carries a 9:16 block, so a
// frame without one fails loudly instead of rendering its 16:9 layout on a tall canvas.
// In 9:16 the split runs across: guest on top, team below the seam at y 760.
//
// usage: node tools/make-vertical.mjs   (then build + render inside vertical/)
import { readFileSync, writeFileSync, mkdirSync, existsSync, symlinkSync } from "node:fs";

const OUT = "vertical";
mkdirSync(`${OUT}/compositions/frames`, { recursive: true });
for (const d of ["assets", "vendor", "audio", "tools", "audio_meta.json", "node_modules"]) {
  if (!existsSync(`${OUT}/${d}`)) symlinkSync(`../${d}`, `${OUT}/${d}`);
}
if (!existsSync(`${OUT}/compositions/lib`)) symlinkSync("../../compositions/lib", `${OUT}/compositions/lib`);

const film = JSON.parse(readFileSync("film.json", "utf8"));
for (const f of film.frames) {
  let s = readFileSync(f.src, "utf8");
  const tag = 'data-width="1920" data-height="1080"';
  if (!s.includes(tag)) throw new Error(`${f.id}: root size declaration not found`);
  if (!s.includes('#root[data-width="1080"]')) throw new Error(`${f.id}: no 9:16 layout block`);
  s = s.replace(tag, 'data-width="1080" data-height="1920"');
  writeFileSync(`${OUT}/${f.src}`, s);
}
const vf = { ...film, width: 1080, height: 1920, _note: ["9:16 cut of ../film.json, generated by tools/make-vertical.mjs"] };
writeFileSync(`${OUT}/film.json`, JSON.stringify(vf, null, 2) + "\n");
console.log(`✓ ${film.frames.length} frames copied into ${OUT}/ with a 1080×1920 root`);
